export interface FunctionSig { name: string; line: number; params: string[] }

export function extractFunctions(code: string, language: string): FunctionSig[] {
  const out: FunctionSig[] = [];
  const lines = code.split(/\r?\n/);
  if (language === "python") {
    const re = /^\s*(?:async\s+)?def\s+(\w+)\s*\(([^)]*)\)/;
    lines.forEach((l, i) => {
      const m = l.match(re);
      if (m) out.push({ name: m[1], line: i + 1, params: m[2].split(",").map(s => s.split("=")[0].replace(/[:*].*/g, "").trim()).filter(Boolean) });
    });
    return out;
  }
  // JS/TS: function decls, const arrow fns, methods
  const re1 = /^\s*(?:export\s+)?(?:async\s+)?function\s+(\w+)\s*\(([^)]*)\)/;
  const re2 = /^\s*(?:export\s+)?const\s+(\w+)\s*=\s*(?:async\s*)?\(([^)]*)\)\s*=>/;
  lines.forEach((l, i) => {
    const m = l.match(re1) || l.match(re2);
    if (m) out.push({ name: m[1], line: i + 1, params: m[2].split(",").map(s => s.replace(/[:?].*/g, "").trim()).filter(Boolean) });
  });
  return out;
}

export function generateTests(sigs: FunctionSig[], moduleName: string, language: string): string {
  const head = language === "python"
    ? `import pytest\nfrom ${moduleName} import ${sigs.map(s => s.name).join(", ")}\n\n# Generated by AI Code Verifier — critical cases only\n`
    : `import { ${sigs.map(s => s.name).join(", ")} } from "./${moduleName}";\n\n// Generated by AI Code Verifier — critical cases only\n`;

  const cases = sigs.map(s => {
    const args = s.params.map(p => p.toLowerCase().includes("list") || p.toLowerCase().includes("arr") ? "[]" : p.toLowerCase().includes("obj") || p.toLowerCase().includes("dict") ? "{}" : "null");
    const callArgs = s.params.map(() => "null");
    if (language === "python") {
      return `def test_${s.name}_null_input():\n    with pytest.raises((TypeError, ValueError)):\n        ${s.name}(${callArgs.join(", ")})\n\ndef test_${s.name}_happy_path():\n    assert ${s.name}(${s.params.map(() => "1").join(", ")}) is not None\n`;
    }
    return `describe("${s.name}", () => {\n  it("rejects null/undefined input", () => {\n    expect(() => ${s.name}(${callArgs.join(", ")})).toThrow();\n  });\n\n  it("handles empty collections", () => {\n    const result = ${s.name}(${args.join(", ")});\n    expect(result).toBeDefined();\n  });\n});\n`;
  });

  return head + "\n" + cases.join("\n");
}
